"""Определение пола участника по ФИО — эвристика для раздельных лидербордов.

Правила идут от самого надёжного признака к самому слабому: отчество →
явный словарь имён → фамилия → окончание имени. Если ничего не сработало,
возвращаем None: лучше не показать человека в топе, чем показать не в том.

Эвристика не может быть точной на 100% (особенно на редких именах и на
транслитерации), поэтому пол хранится в БД отдельным полем и правится
админом вручную — см. participants.gender и кнопку в карточке участника.
"""
from __future__ import annotations

# Женские имена, которые не ловятся окончанием (согласная или мягкий знак).
FEMALE_NAMES = {
    "любовь", "нинель", "гузель", "асель", "айгуль", "гульнур", "жанель",
    "адель", "нурай", "динар", "эльнур", "сюмбель", "рахель", "рут", "эстер",
    "дилноз", "мохинур", "гулнур", "шохсанам", "олтиной", "гулбахор",
}
# Мужские имена, оканчивающиеся на -а/-я (иначе их приняло бы за женские).
MALE_NAMES = {
    "никита", "илья", "данила", "данило", "савва", "фома", "лука", "кузьма",
    "гоша", "миша", "паша", "саша", "женя", "дима", "лёша", "леша", "коля",
    "толя", "витя", "серёжа", "сережа", "юра", "слава", "вова", "ваня",
    "костя", "петя", "стёпа", "степа", "яша", "муса", "иса", "мустафа",
    "жура", "хамза", "мирза", "ага",
}

_FEM_PATRONYMIC = ("овна", "евна", "ична", "инична", "кызы", "қизи", "кизи", "qizi")
_MAL_PATRONYMIC = ("ович", "евич", "ьич", "ич", "угли", "ўғли", "оглы", "ogli",
                   "oglu", "уулу")
_FEM_SURNAME = ("ова", "ева", "ёва", "ина", "ына", "ская", "цкая", "ая", "яя")
_MAL_SURNAME = ("ов", "ев", "ёв", "ин", "ын", "ский", "цкий", "ой", "ый", "ев",
                "оглы")


def _norm(s: str) -> str:
    return s.lower().replace("ё", "е").strip(".,()[]{}«»\"'-")


def detect_gender(full_name: str | None) -> str | None:
    """'f' | 'm' | None (не определили) по строке ФИО."""
    if not full_name:
        return None
    parts = [_norm(p) for p in full_name.split() if _norm(p)]
    if not parts:
        return None

    # 1. Отчество / узбекские «қизи» и «ўғли» — самый надёжный признак.
    for p in parts[1:]:
        if p.endswith(_FEM_PATRONYMIC):
            return "f"
        if p.endswith(_MAL_PATRONYMIC) and len(p) > 4:
            return "m"

    # 2. Явные словари имён (личное имя обычно второе, но пишут по-разному).
    for p in parts[:3]:
        if p in FEMALE_NAMES:
            return "f"
        if p in MALE_NAMES:
            return "m"

    # 3. Фамилия.
    surname = parts[0]
    if surname.endswith(_FEM_SURNAME):
        return "f"
    if surname.endswith(_MAL_SURNAME) and len(surname) > 3:
        return "m"

    # 4. Окончание личного имени — самый слабый признак.
    name = parts[1] if len(parts) > 1 else parts[0]
    if len(name) < 3:
        return None
    if name.endswith(("а", "я")):
        return "f"
    if name[-1] in "бвгджзйклмнпрстфхцчшщ":
        return "m"
    return None


